def emit_obj(obj: dict, indent: int = 2) -> str:
    pad = " " * indent
    lines = ["{"]
    items = list(obj.items())
    for i, (key, value) in enumerate(items):
        comma = "," if i < len(items) - 1 else ""
        if isinstance(value, dict):
            nested = emit_obj(value, indent + 2)
            lines.append(f"{pad}{key}: {nested}{comma}")
        else:
            escaped = (
                value.replace("\\", "\\\\")
                .replace("'", "\\'")
                .replace("\n", "\\n")
            )
            lines.append(f"{pad}{key}: '{escaped}'{comma}")
    lines.append(" " * (indent - 2) + "}")
    return "\n".join(lines)


def flatten_keys(obj: dict, prefix: str = "") -> set[str]:
    keys: set[str] = set()
    for k, v in obj.items():
        path = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict):
            keys.update(flatten_keys(v, path))
        else:
            keys.add(path)
    return keys


